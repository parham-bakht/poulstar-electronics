i2c = SoftI2C(sda = Pin(4), scl = Pin(5), freq = 400000)
oled = SSD1306_I2C(128, 64, i2c)

rtc = ds3231.RTC(sda_pin= 21, scl_pin= 22)
rtc.SetTime(hours= 18, minutes= 47, seconds= 0, weekday= 2, day= 22, month= 10, year= 23)


def draw_image(image, width, height):
    for y in range(height):
        for x in range(width):
            byte_index = (x + (y // 8) * width) % len(image)
            bit = (image[byte_index] >> (y % 8)) & 1
            oled.pixel(x, y, bit)


while True:
    
    rtc_time = rtc.ReadTime("time")
    rtc_weekday = rtc.ReadTime("weekday")
    print(rtc_weekday)
    hour, minute, second = rtc_time.split(":")
    
    oled.fill(0)    #erase everything before writing again
    display_clock(oled, int(hour), int(minute), int(second))
    draw_image(image_byteArray,64,33)    
    oled.text(rtc_weekday,0,33)
    oled.text(rtc_time,0,42)
    
    oled.show()
    
    time.sleep(1)